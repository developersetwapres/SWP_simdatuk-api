    public function flattenArray($array, &$result = [])
    {
        foreach ($array as $item) {
            // Remove 'child' key if it exists and add current item to the result
            $currentItem = $item;
            if (isset($currentItem['child'])) {
                unset($currentItem['child']);
            }
            $result[] = $currentItem;

            // Recursively call flattenArray if 'child' key exists
            if (isset($item['child'])) {
                $this->flattenArray($item['child'], $result);
            }
        }
        return $result;
    }

